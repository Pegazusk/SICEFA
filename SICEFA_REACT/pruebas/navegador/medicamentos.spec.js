import { test, expect } from '@playwright/test'

test('los 48 medicamentos iniciales cargan su foto, también en el detalle', async ({ page }, info) => {
  await page.goto('/')
  await page.getByLabel('Administrador').fill('AG20230901')
  await page.getByLabel('Contraseña', { exact: true }).fill('AG20230901')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Producto', exact: true }).click()
  const response = await page.request.get('/api/productos')
  const products = (await response.json()).filter(product => product.id <= 48)
  expect(products).toHaveLength(48)
  for (const product of products) expect(product.foto).toMatch(/^\/img\/.+\.(jpg|png)$/)
  const failed = await page.evaluate(async products => {
    const results = await Promise.all(products.map(async product => {
      const image = new Image()
      image.src = product.foto
      try { await image.decode(); return image.naturalWidth > 0 ? null : product.nombre }
      catch { return product.nombre }
    }))
    return results.filter(Boolean)
  }, products)
  expect(failed).toEqual([])
  await page.screenshot({ path: `docs/fotos-reales-${info.project.name}.png`, fullPage: true })
  await page.getByLabel('Buscar productos').fill('Naproxeno')
  await page.getByRole('button', { name: 'Ver información de Naproxeno', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const picture = dialog.getByRole('img', { name: 'Naproxeno', exact: true })
  await expect(picture).toHaveAttribute('src', '/img/medicamentos/naproxeno.jpg')
  await expect.poll(() => picture.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true)
  expect((await picture.boundingBox()).width).toBeGreaterThan(260)
  await dialog.screenshot({ path: `docs/foto-real-detalle-${info.project.name}.png` })
})

test('la cuadrícula permite cambiar de página, ordenar y ver el detalle completo', async ({ page }, info) => {
  await page.goto('/')
  await page.getByLabel('Administrador').fill('AG20230901')
  await page.getByLabel('Contraseña', { exact: true }).fill('AG20230901')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Producto', exact: true }).click()
  const grid = page.locator('.product-grid')
  await expect(grid.locator('article')).toHaveCount(12)
  const columns = await grid.evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length)
  expect(columns).toBe(info.project.name === 'desktop' ? 4 : 2)
  const firstName = await grid.locator('.product-card-name').first().innerText()
  await page.getByRole('button', { name: 'Página siguiente' }).click()
  await expect(page.getByLabel(/Página 2 de/)).toBeVisible()
  await expect(grid.locator('.product-card-name').first()).not.toHaveText(firstName)
  await page.getByLabel('Ordenar medicamentos').selectOption('precio-menor')
  await expect(page.getByLabel(/Página 1 de/)).toBeVisible()
  const prices = await grid.locator('.product-card-price').allTextContents()
  const values = prices.map(price => Number(price.replace(/[^\d.]/g, '')))
  expect(values).toEqual([...values].sort((a, b) => a - b))
  await page.getByLabel('Buscar productos').fill('Donepezilo')
  await page.getByRole('button', { name: 'Ver información de Donepezilo', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Donepezilo', exact: true })).toBeVisible()
  for (const text of ['10 mg', 'Envase con 14 tabletas', 'Enfermedad de Alzheimer', 'Hipersensibilidad', 'Código de barras']) await expect(dialog).toContainText(text)
  const picture = dialog.getByRole('img', { name: 'Donepezilo', exact: true })
  await expect(picture).toBeVisible()
  await expect.poll(() => picture.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true)
  expect((await picture.boundingBox()).width).toBeGreaterThan(260)
  await dialog.screenshot({ path: `docs/medicamento-detalle-${info.project.name}.png` })
  await dialog.getByRole('button', { name: 'Editar medicamento' }).click()
  await expect(page.getByRole('dialog').getByLabel('Nombre *', { exact: true })).toHaveValue('Donepezilo')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByLabel('Buscar productos').fill('Paracetamol')
  await page.route('**/img/paracetamol.png', route => route.abort())
  await page.getByRole('button', { name: 'Ver información de Paracetamol', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Fotografía no disponible')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
