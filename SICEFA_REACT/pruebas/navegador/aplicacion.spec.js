import { test, expect } from '@playwright/test'

async function login(page, mode = 'central') {
  await page.goto('/')
  if (mode === 'sucursal') await page.getByRole('button', { name: 'Ir a Sucursal' }).click()
  await page.getByLabel(mode === 'central' ? 'Administrador' : 'Usuario de sucursal').fill('AG20230901')
  await page.getByLabel('Contraseña', { exact: true }).fill('AG20230901')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bienvenido, Alvaro.' })).toBeVisible()
}

test('inicio de sesión, menú, recarga con sesión, perfil y salida', async ({ page }, info) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Todo listo para comenzar.' })).toBeVisible()
  await page.screenshot({ path: `docs/login-${info.project.name}.png`, fullPage: true })
  await page.getByLabel('Administrador').fill('AG20230901')
  await page.getByLabel('Contraseña', { exact: true }).fill('incorrecta')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Usuario o contraseña incorrectos')
  await page.getByLabel('Contraseña', { exact: true }).fill('AG20230901')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bienvenido, Alvaro.' })).toBeVisible()
  await page.screenshot({ path: `docs/inicio-${info.project.name}.png`, fullPage: true })
  for (const [link, heading] of [['Sucursal', 'Sucursales'], ['Producto', 'Productos'], ['Empleado', 'Empleados'], ['Cliente', 'Clientes']]) {
    await page.getByRole('navigation').getByRole('link', { name: link, exact: true }).click()
    await expect(page.getByRole('heading', { name: heading, exact: true })).toBeVisible()
    await expect(page.locator(link === 'Producto' ? '.product-card' : 'tbody tr').first()).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    if (link === 'Producto') await page.screenshot({ path: `docs/productos-${info.project.name}.png`, fullPage: true })
  }
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Clientes', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Mi perfil', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Alvaro Gomez')
  await page.getByRole('button', { name: 'Cerrar ventana' }).click()
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Todo listo para comenzar.' })).toBeVisible()
  expect(errors).toEqual([])
})

test('agregar, editar, buscar, dar de baja y reactivar un producto se conserva al recargar', async ({ page }, info) => {
  const name = `Producto E2E ${info.project.name}`
  await login(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Producto', exact: true }).click()
  await page.getByRole('button', { name: 'Agregar producto' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre *', { exact: true }).fill(name)
  await dialog.getByLabel('Nombre genérico').fill('Genérico de prueba')
  await dialog.getByLabel('Precio unitario (MXN)').fill('29.50')
  await dialog.getByLabel('Presentación').fill('Caja con 10 unidades')
  await dialog.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByLabel('Buscar productos').fill(name)
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('button', { name: `Editar ${name}`, exact: true }).click()
  await expect(dialog.getByLabel('Nombre *', { exact: true })).toHaveValue(name)
  await dialog.getByLabel('Precio unitario (MXN)').fill('35.75')
  await dialog.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await page.getByLabel('Buscar productos').fill(name)
  await expect(page.locator('.product-grid')).toContainText('$35.75')
  await page.getByRole('button', { name: `Dar de baja ${name}`, exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirmar' }).click()
  await expect(page.getByText('No encontramos registros')).toBeVisible()
  await page.getByRole('button', { name: 'Inactivos', exact: true }).click()
  await page.getByRole('button', { name: `Reactivar ${name}`, exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirmar' }).click()
  await page.getByRole('button', { name: 'Activos', exact: true }).click()
  await expect(page.locator('.product-grid')).toContainText(name)
})

test('la sucursal registra compras y ventas y respeta los permisos de productos', async ({ page }, info) => {
  await login(page, 'sucursal')
  const nav = page.getByRole('navigation')
  await nav.getByRole('link', { name: 'Productos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Productos', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Agregar producto' })).toHaveCount(0)
  await page.getByLabel('Buscar productos').fill('Paracetamol')
  await page.getByRole('button', { name: 'Ver información de Paracetamol', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('500 mg')
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Editar medicamento' })).toHaveCount(0)
  await page.getByRole('dialog').getByRole('button', { name: 'Cerrar', exact: true }).click()
  await nav.getByRole('link', { name: 'Compra', exact: true }).click()
  await page.getByLabel('Producto *').selectOption('1')
  await page.getByLabel('Cantidad *').fill('3')
  await page.getByRole('button', { name: 'Realizar pedido' }).click()
  await expect(page.locator('tbody tr').first()).toContainText('Pendiente')
  await page.locator('tbody tr').first().getByRole('button', { name: 'Recibir' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirmar' }).click()
  await expect(page.locator('tbody tr').first()).toContainText('Recibido')
  await nav.getByRole('link', { name: 'Ventas', exact: true }).click()
  await page.getByLabel('Cliente *').selectOption('1')
  await page.getByLabel('Producto *').selectOption('1')
  await page.getByLabel('Cantidad *').fill('2')
  await page.getByRole('button', { name: 'Registrar venta' }).click()
  await expect(page.locator('tbody tr').first()).toContainText('$933.80')
  await page.reload()
  await expect(page.locator('tbody tr').first()).toContainText('Registrada')
  await page.screenshot({ path: `docs/ventas-${info.project.name}.png`, fullPage: true })
  await page.locator('tbody tr').first().getByRole('button', { name: 'Cancelar' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirmar' }).click()
  await expect(page.locator('tbody tr').first()).toContainText('Cancelada')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
